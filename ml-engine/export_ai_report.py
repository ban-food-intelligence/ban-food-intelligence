"""Builds the AI evaluation block of database-mysql/seed.sql.

    python ml-engine/export_ai_report.py

It reads the time-split results of train_model_ali.py (artifacts/ali/metrics.json and the
out-of-fold/test predictions) and writes, between the markers in seed.sql:

* ml_model_metric rows: model vs baseline MAE and MAPE on the held-out (latest) test period
  - production: packages (actual_qty) and EKP; butchery: part weights in kg.
* ml_prediction rows for the baseline ("historical mean ratio") on the seeded demo
  records, next to the model predictions that predict_ali.py already emitted.

Baseline = mean ratio of the training period only:
  production: mean yield_pct of the product -> packages = meat_kg x yield / pack size;
  butchery:   mean part share per species   -> kg = share x input weight.
Data is synthetic (see generator_ali.py); the block says so.
"""
from __future__ import annotations

import json
import pathlib

import numpy as np
import pandas as pd

ROOT = pathlib.Path(__file__).resolve().parent
SEED = ROOT.parent / "database-mysql" / "seed.sql"
BEGIN = "-- BEGIN ai-report (generated by ml-engine/export_ai_report.py; do not edit by hand)"
END = "-- END ai-report"
PARTS = ["but", "sirt", "omuz", "kaburga", "kiyma", "fire"]
CHAMPION = "ali_ridge"

# Seeded demo records (seed.sql): inputs needed to turn ratios into packages / kg / EKP.
SEED_ORDERS = {
    # order_no: (meat_kg, pack_size_kg, material_cost_eur, service_eur_per_pack)
    "URT-2026-045": (100.0, 1.0, 1076.00, 5.50),
    "URT-2026-046": (100.0, 1.0, 1091.00, 5.50),
}
SEED_BUTCHERY = {"PRC-2026-001": ("KUZU", 25.0)}


def mae_mape(y: np.ndarray, p: np.ndarray) -> tuple[float, float]:
    mask = y != 0
    return float(np.mean(np.abs(y - p))), float(100 * np.mean(np.abs((y[mask] - p[mask]) / y[mask])))


def production_metrics(metrics: dict) -> list[tuple]:
    rows = []
    n = metrics["production"]["n_test"]
    for name, role in [(CHAMPION, "MODEL"), ("baseline_hist_mean", "BASELINE"), ("baseline_recipe", "BASELINE")]:
        m = metrics["production"]["models"][name]
        rows.append(("PRODUCTION", "actual_qty", "paket", name, role, n, m["test_actual_qty"]["MAE"], m["test_actual_qty"]["MAPE_pct"]))
        rows.append(("PRODUCTION", "ekp", "EUR", name, role, n, m["test_ekp_eur"]["MAE"], m["test_ekp_eur"]["MAPE_pct"]))
    return rows


def butchery_metrics() -> tuple[list[tuple], pd.Series]:
    data = pd.read_csv(ROOT / "data" / "train_task4b_ali.csv")
    oof = pd.read_csv(ROOT / "artifacts" / "ali" / "oof_ali_butchery.csv")
    split = oof.drop_duplicates("row_id").set_index("row_id")["split"]
    data["split"] = data["row_id"].map(split)
    train, test = data[data.split == "train"], data[data.split == "test"].copy()
    pct_cols = [f"{p}_pct" for p in PARTS]
    kg_true = test[[f"{p}_kg" for p in PARTS]].to_numpy()
    w = test["carcass_weight_kg"].to_numpy()[:, None]

    model = oof[(oof.split == "test") & (oof.model == CHAMPION)].pivot(index="row_id", columns="target", values="y_pred")
    model = model.loc[test.row_id, pct_cols].to_numpy()
    model = model / model.sum(axis=1, keepdims=True) * 100  # same normalisation as predict_ali.py

    hist = train.groupby("species")[pct_cols].mean()
    base_hist = hist.loc[test.species].to_numpy()
    recipe = {"KUZU": [26, 14, 20, 12, 16, 12]}
    base_recipe = np.vstack([recipe.get(s, hist.loc[s].to_list()) for s in test.species]).astype(float)

    rows = []
    n = len(test)
    for name, role, pct in [(CHAMPION, "MODEL", model), ("baseline_hist_mean", "BASELINE", base_hist), ("baseline_recipe", "BASELINE", base_recipe)]:
        kg = pct / 100 * w
        mae, mape = mae_mape(kg_true[:, :5].ravel(), kg[:, :5].ravel())  # sellable parts
        rows.append(("BUTCHERY", "part_kg", "kg", name, role, n, mae, mape))
        mae, mape = mae_mape(kg_true[:, 5], kg[:, 5])
        rows.append(("BUTCHERY", "fire_kg", "kg", name, role, n, mae, mape))
    return rows, hist.loc["KUZU"]


def main() -> None:
    metrics = json.loads((ROOT / "artifacts" / "ali" / "metrics.json").read_text(encoding="utf-8"))
    prod = pd.read_csv(ROOT / "data" / "train_task4a_ali.csv")
    oofp = pd.read_csv(ROOT / "artifacts" / "ali" / "oof_ali_production.csv").drop_duplicates("row_id").set_index("row_id")["split"]
    prod["split"] = prod["row_id"].map(oofp)
    mean_yield = float(prod[(prod.split == "train") & (prod.product_sku == "MM-SUCUK-1KG")]["yield_pct"].mean())

    metric_rows = production_metrics(metrics)
    b_rows, kuzu_share = butchery_metrics()
    metric_rows += b_rows

    out = [BEGIN, "-- Synthetic training data (generator_ali.py); test = latest 20% of dates (time split).",
           "USE food_intel;"]
    for task, target, unit, model, role, n, mae, mape in metric_rows:
        out.append(
            "INSERT INTO ml_model_metric (task, target_name, unit, model_name, role, eval_split, n_rows, mae, mape_pct) "
            f"VALUES ('{task}', '{target}', '{unit}', '{model}', '{role}', 'TEST_TIME_SPLIT', {n}, {mae:.4f}, {mape:.4f});")

    for order_no, (meat_kg, pack, material, service) in SEED_ORDERS.items():
        qty = meat_kg * mean_yield / 100 / pack
        ekp = (material + qty * service) / qty
        ref = f"(SELECT id FROM production_order WHERE order_no = '{order_no}')"
        actual_qty = f"(SELECT actual_qty FROM production_order WHERE order_no = '{order_no}')"
        actual_ekp = f"(SELECT unit_cost FROM production_output pout JOIN production_order po ON po.id = pout.production_order_id WHERE po.order_no = '{order_no}' LIMIT 1)"
        for target, task, value, actual in [("actual_qty", "PRODUCTION_YIELD", qty, actual_qty), ("ekp", "PRODUCTION_EKP", ekp, actual_ekp)]:
            out.append(
                "INSERT INTO ml_prediction (task, model_name, model_version, ref_type, ref_id, target_name, predicted_value, actual_value) "
                f"VALUES ('{task}', 'baseline_hist_mean', 'baseline-1', 'production_order', {ref}, '{target}', {value:.4f}, {actual});")

    for op_no, (species, weight) in SEED_BUTCHERY.items():
        ref = f"(SELECT id FROM butchery_operation WHERE op_no = '{op_no}')"
        for part in PARTS:
            kg = kuzu_share[f"{part}_pct"] / 100 * weight
            sku = {"but": "KZ-BUT", "sirt": "KZ-SIRT", "omuz": "KZ-OMUZ", "kaburga": "KZ-KABURGA", "kiyma": "KZ-KIYMA", "fire": "KZ-FIRE"}[part]
            actual = f"(SELECT SUM(o.weight_kg) FROM butchery_output o JOIN product p ON p.id = o.product_id WHERE o.operation_id = {ref} AND p.sku = '{sku}')"
            out.append(
                "INSERT INTO ml_prediction (task, model_name, model_version, ref_type, ref_id, target_name, predicted_value, actual_value) "
                f"VALUES ('BUTCHERY_YIELD', 'baseline_hist_mean', 'baseline-1', 'butchery_operation', {ref}, '{part}_kg', {kg:.4f}, {actual});")
    out.append(END)
    block = "\n".join(out) + "\n"

    seed = SEED.read_text(encoding="utf-8")
    if BEGIN in seed:
        seed = seed[: seed.index(BEGIN)] + block + seed[seed.index(END) + len(END) + 1:]
    else:
        seed = seed.rstrip("\n") + "\n\n" + block
    SEED.write_text(seed, encoding="utf-8", newline="\n")
    print(f"mean yield (train) {mean_yield:.3f}%  -> {len(metric_rows)} metric rows written to {SEED.name}")
    for r in metric_rows:
        print(f"  {r[0]:10s} {r[1]:10s} {r[3]:20s} MAE {r[6]:.3f} {r[2]:5s} MAPE {r[7]:.2f}%")


if __name__ == "__main__":
    main()
